// Python and Rust embed this immutable renderer in their own QuickJS runtimes.
// Regenerate the checked-in resource from the JS release source. No network.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const output = process.argv[2];
if (!output) throw new Error("Usage: node scripts/build-sprite-core.mjs OUTPUT [--check]");
const read = (name) => readFile(fileURLToPath(new URL("../src/" + name, import.meta.url)), "utf8");
const modules = ["gltf-scene.mjs", "sprite-model.mjs", "sprite-slices.mjs", "sprite-projection.mjs"];
let body = "";
for (const name of modules) {
  const source = (await read(name))
    .replace(/^import \{[^}]+\} from "\.\/[^"]+";\s*$/gm, "")
    .replace(/^export (?=(?:async )?function )/gm, "");
  if (/^(import|export)\b/m.test(source)) throw new Error("Unexpected import/export in " + name);
  body += "// " + name + "\n" + source.trim() + "\n";
}
const bridge = await readFile(new URL("./sprite-host.js", import.meta.url), "utf8");
const result =
  "// Generated by nanoodle-js/scripts/build-sprite-core.mjs.\n(function(){\n" + body + bridge + "\n})();\n";
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== result) throw new Error("Stale sprite renderer: " + output);
} else await writeFile(output, result);
